import type { Branding } from "./branding.types";
import { BRANDING_KEYS } from "./branding.types";

export type { Branding };

export function assertBranding(value: unknown): Branding {
  if (value === null || typeof value !== "object") {
    throw new Error("branding.json must be an object");
  }
  const record = value as Record<string, unknown>;
  const missing = BRANDING_KEYS.filter((key) => {
    const v = record[key];
    return typeof v !== "string" || v.trim().length === 0;
  });
  if (missing.length > 0) {
    throw new Error(`branding.json missing or empty keys: ${missing.join(", ")}`);
  }
  const npmScope = record.npmScope as string;
  if (!npmScope.startsWith("@") || npmScope.includes("/")) {
    // `bonne-garde add` rewrites the scope in this line, so the formatter cannot know how wide it is.
    // oxfmt-ignore
    throw new Error('branding.npmScope must look like "@acme" (no slash)');
  }
  return {
    displayName: record.displayName as string,
    shortName: record.shortName as string,
    description: record.description as string,
    lang: record.lang as string,
    themeColor: record.themeColor as string,
    backgroundColor: record.backgroundColor as string,
    npmScope,
    publicOrigin: record.publicOrigin as string,
    supportEmail: record.supportEmail as string,
    legalName: record.legalName as string,
  };
}

export function renderBrandingModule(branding: Branding): string {
  const body = BRANDING_KEYS.map((key) => `  ${key}: ${JSON.stringify(branding[key])},`).join("\n");
  return `/**
 * GENERATED FILE — do not edit by hand.
 * Source: branding.json · Regenerated by \`vp run gen:branding\`
 */
import type { Branding } from "./branding.types";

export const branding = {
${body}
} as const satisfies Branding;

export type { Branding };
`;
}

/** The two sizes an installable web app needs, named by root URL: the favicons are served from the site root. */
const MANIFEST_ICONS = [
  {
    src: "/android-chrome-192x192.png",
    sizes: "192x192",
    type: "image/png",
    purpose: "maskable any",
  },
  {
    src: "/android-chrome-512x512.png",
    sizes: "512x512",
    type: "image/png",
    purpose: "maskable any",
  },
];

export function renderWebManifest(branding: Branding): string {
  const manifest = {
    name: branding.displayName,
    short_name: branding.shortName,
    description: branding.description,
    start_url: "/",
    display: "standalone",
    background_color: branding.backgroundColor,
    theme_color: branding.themeColor,
    orientation: "portrait",
    scope: "/",
    lang: branding.lang,
    icons: MANIFEST_ICONS,
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

export function formatEmailFrom(legalOrDisplayName: string, address: string): string {
  return `${legalOrDisplayName} <${address}>`;
}

export function slugFromNpmScope(npmScope: string): string {
  return npmScope.startsWith("@") ? npmScope.slice(1) : npmScope;
}
